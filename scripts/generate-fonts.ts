// Generates src/pdf/font-data.ts from the DejaVu TTFs in src/fonts/.
//
// The PDF is built in the browser by @react-pdf/renderer, which registers a font from a URL. Both
// hosts (the plugin's static bundle at /tour and the IDE, which compiles these sources directly)
// must work without the host serving a font file, so the TTFs travel as base64 data URLs inside a
// plain TypeScript module. They are subset first: the report needs Latin (pt-BR accents), Greek
// and Cyrillic (project data) plus the punctuation, arrow and math symbols the evidence contains —
// about a third of the full DejaVu coverage.
//
// Run with `bun run fonts`; the generated file is committed so a fresh clone builds and tests
// without running this first.

import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import subsetFont from 'subset-font';

/** The character ranges the report can contain. */
const RANGES: readonly [number, number][] = [
  [0x20, 0x24f], // basic Latin, Latin-1 supplement, Latin extended-A and -B
  [0x370, 0x4ff], // Greek and Cyrillic (project data is not translated)
  [0x2000, 0x206f], // general punctuation: – — ‘ ’ “ ” …
  [0x20a0, 0x20cf], // currency symbols
  [0x2100, 0x214f], // letterlike symbols
  [0x2190, 0x21ff], // arrows: → ←
  [0x2200, 0x22ff], // mathematical operators: ≠ ≤ ≥ ×
  [0x2500, 0x25ff], // box drawing, block elements, geometric shapes: • ▪
  [0x2700, 0x27bf] // dingbats: ✔ ✘
];

const FONTS: readonly { file: string; exportName: string }[] = [
  { file: 'DejaVuSans.ttf', exportName: 'DEJAVU_SANS' },
  { file: 'DejaVuSans-Bold.ttf', exportName: 'DEJAVU_SANS_BOLD' },
  { file: 'DejaVuSansMono.ttf', exportName: 'DEJAVU_SANS_MONO' },
  { file: 'DejaVuSansMono-Bold.ttf', exportName: 'DEJAVU_SANS_MONO_BOLD' }
];

const root = fileURLToPath(new URL('..', import.meta.url));
const text = RANGES.flatMap(([from, to]) => {
  const chars: string[] = [];
  for (let code = from; code <= to; code++) chars.push(String.fromCodePoint(code));
  return chars;
}).join('');

const lines: string[] = [
  '// Generated by scripts/generate-fonts.ts from src/fonts/*.ttf — do not edit.',
  '// Subset DejaVu fonts as base64 data URLs, registered with @react-pdf/renderer (src/pdf/fonts.ts).',
  ''
];

let total = 0;
for (const font of FONTS) {
  const source = readFileSync(`${root}/src/fonts/${font.file}`);
  const subset = await subsetFont(source, text, { targetFormat: 'sfnt' });
  total += subset.length;
  lines.push(`export const ${font.exportName} = 'data:font/ttf;base64,${Buffer.from(subset).toString('base64')}';`, '');
  console.log(`${font.file}: ${source.length} -> ${subset.length} bytes`);
}

writeFileSync(`${root}/src/pdf/font-data.ts`, `${lines.join('\n')}\n`);
console.log(`src/pdf/font-data.ts written (${total} font bytes, ~${Math.ceil((total * 4) / 3)} as base64)`);
